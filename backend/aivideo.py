"""
AI video clips — generated by a third-party model (Replicate).

The storyboard tool (backend/studio.py) composes a video in the browser from
the merchant's own photos. This module is the other half: it asks a hosted
video model to *generate the footage itself* from a text description, or to
animate one product photo.

Provider
--------
Replicate's HTTP API (https://replicate.com/docs/reference/http):
  POST /v1/predictions        {"version": "<owner>/<model>", "input": {...}}
  GET  /v1/predictions/{id}   status: starting | processing | succeeded | failed | canceled
Outputs are deleted by Replicate an hour after the run, so a finished clip is
downloaded once and kept under VIDEO_DIR/<tenant>/<job>.mp4 — or, when an
S3-compatible bucket is configured (backend/objstore.py, e.g. Cloudflare R2),
uploaded there so it survives redeploys, and served by a short-lived link.

The default model is bytedance/seedance-1-lite (text-to-video and image-to-
video, 4–12 s, 480p/720p; priced per second of output). Its input fields are
prompt, image, duration, resolution and aspect_ratio. Another model can be set
with VIDEO_MODEL as long as it accepts the same fields.

Every clip costs the operator real money, so clips are metered per plan
(PLANS[...]["monthly_ai_videos"]); a clip that fails is not counted.

Config (env)
------------
  REPLICATE_API_TOKEN   enables the feature (alias: VIDEO_API_TOKEN)
  VIDEO_MODEL           default bytedance/seedance-1-lite
  VIDEO_RESOLUTION      default 720p

Endpoints
---------
  GET    /studio/videos/config     Is it on, which lengths, this month's usage
  POST   /studio/videos            Start a clip
  GET    /studio/videos            This workspace's clips, newest first
  GET    /studio/videos/{id}       One clip; refreshes it from the provider while it runs
  GET    /studio/videos/{id}/file  The finished MP4
  DELETE /studio/videos/{id}
"""
import json
import logging
import os
import re
import threading
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse, RedirectResponse
from pydantic import BaseModel, Field

from backend import activity, ratelimit, repo
from backend.auth import current_user, require_tenant
from backend.billing import PLANS, plan_limits
from backend import objstore
from backend.db import VIDEO_DIR

router = APIRouter()
log = logging.getLogger("kol.aivideo")

API_BASE = "https://api.replicate.com/v1"
TOKEN = (os.environ.get("REPLICATE_API_TOKEN") or os.environ.get("VIDEO_API_TOKEN") or "").strip()
MODEL = (os.environ.get("VIDEO_MODEL") or "bytedance/seedance-1-lite").strip()
RESOLUTION = (os.environ.get("VIDEO_RESOLUTION") or "720p").strip()
DURATIONS = (5, 10)
ASPECTS = ("9:16", "1:1", "16:9")
KIND = "ai_video"
RUNNING = ("starting", "processing")
_GIVE_UP_AFTER = timedelta(minutes=30)
_MAX_BYTES = 150 * 1024 * 1024
_DATA_URL = re.compile(r"^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$")
_lock = threading.Lock()


def enabled() -> bool:
    return bool(TOKEN)


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _month() -> str:
    return _now().strftime("%Y-%m")


# ── Provider calls (tests replace these three) ────────────────────
def _request(method: str, url: str, body: Optional[dict] = None, extra: Optional[dict] = None) -> dict:
    req = urllib.request.Request(url, method=method,
                                 data=json.dumps(body).encode("utf-8") if body is not None else None)
    req.add_header("Authorization", "Bearer " + TOKEN)
    req.add_header("Content-Type", "application/json")
    for k, v in (extra or {}).items():
        req.add_header(k, v)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode("utf-8") or "{}")


def provider_create(model_input: dict) -> dict:
    # Cancel-After stops a stuck run from billing indefinitely.
    return _request("POST", API_BASE + "/predictions", {"version": MODEL, "input": model_input},
                    {"Cancel-After": "20m"})


def provider_get(prediction_id: str) -> dict:
    return _request("GET", f"{API_BASE}/predictions/{prediction_id}")


def provider_download(url: str, path: str) -> int:
    """Save the output file; returns its size. Output files may need the token."""
    req = urllib.request.Request(url)
    req.add_header("Authorization", "Bearer " + TOKEN)
    size = 0
    with urllib.request.urlopen(req, timeout=120) as r, open(path + ".part", "wb") as f:
        while True:
            chunk = r.read(1 << 16)
            if not chunk:
                break
            size += len(chunk)
            if size > _MAX_BYTES:
                raise ValueError("output too large")
            f.write(chunk)
    os.replace(path + ".part", path)
    return size


# ── helpers ───────────────────────────────────────────────────────
def _path(tenant_id: str, job_id: int) -> str:
    return os.path.join(VIDEO_DIR, re.sub(r"[^A-Za-z0-9_-]", "", tenant_id), f"{int(job_id)}.mp4")


def _object_key(tenant_id: str, job_id: int) -> str:
    return "videos/" + re.sub(r"[^A-Za-z0-9_-]", "", tenant_id) + f"/{int(job_id)}.mp4"


def delete_bucket_files(tenant_id: str) -> None:
    """Best effort: remove a workspace's clips from object storage."""
    if not objstore.enabled():
        return
    for j in repo.docs_list(tenant_id, KIND, limit=1000):
        if j.get("stored") == "bucket":
            try:
                objstore.delete(_object_key(tenant_id, j["id"]))
            except Exception:
                pass


def _public(job: dict) -> dict:
    out = {k: job.get(k) for k in ("id", "created_at", "status", "prompt", "duration", "aspect",
                                    "has_image", "error", "size", "created_by", "finished_at")}
    out["ready"] = job.get("status") == "succeeded"
    return out


def _used_this_month(tenant_id: str) -> int:
    month = _month()
    return sum(1 for j in repo.docs_list(tenant_id, KIND, limit=1000)
               if (j.get("created_at") or "")[:7] == month and j.get("status") != "failed")


def _limit(tenant_id: str) -> Optional[int]:
    from backend import growth
    if growth.trial_active(tenant_id):          # clips cost real money: a trial keeps the Free allowance
        return PLANS["free"]["monthly_ai_videos"]
    return plan_limits(tenant_id).get("monthly_ai_videos")


def _fail(tenant_id: str, job: dict, reason: str) -> dict:
    job.update(status="failed", error=reason[:200], finished_at=_now().isoformat())
    return repo.doc_put(tenant_id, KIND, job["id"], job) or job


def _refresh(tenant_id: str, job: dict) -> dict:
    """Bring a running job up to date with the provider; download when done."""
    if job.get("status") not in RUNNING:
        return job
    with _lock:
        job = repo.doc_get(tenant_id, KIND, job["id"]) or job        # another request may have finished it
        if job.get("status") not in RUNNING:
            return job
        if not job.get("prediction_id"):
            return _fail(tenant_id, job, "The video service did not accept the job.")
        try:
            p = provider_get(job["prediction_id"])
        except (urllib.error.URLError, TimeoutError, ValueError) as e:
            log.warning("video status check failed job=%s: %s", job["id"], e)
            created = datetime.fromisoformat(job["created_at"])
            if _now() - created > _GIVE_UP_AFTER:
                return _fail(tenant_id, job, "The video service did not respond in time.")
            return job
        status = p.get("status")
        if status in RUNNING:
            if _now() - datetime.fromisoformat(job["created_at"]) > _GIVE_UP_AFTER:
                return _fail(tenant_id, job, "The video took too long to generate.")
            if status != job["status"]:
                job["status"] = status
                job = repo.doc_put(tenant_id, KIND, job["id"], job) or job
            return job
        if status == "succeeded":
            out = p.get("output")
            url = out[0] if isinstance(out, list) and out else out
            if not isinstance(url, str) or not url.startswith("https://"):
                return _fail(tenant_id, job, "The video service returned no video.")
            path = _path(tenant_id, job["id"])
            os.makedirs(os.path.dirname(path), exist_ok=True)
            try:
                size = provider_download(url, path)
            except (urllib.error.URLError, TimeoutError, OSError, ValueError) as e:
                log.warning("video download failed job=%s: %s", job["id"], e)
                return _fail(tenant_id, job, "The finished video could not be downloaded.")
            if objstore.enabled():
                try:
                    objstore.put_file(_object_key(tenant_id, job["id"]), path, "video/mp4")
                    job["stored"] = "bucket"
                    os.remove(path)
                except (urllib.error.URLError, TimeoutError, OSError) as e:
                    # keep the local copy; it still works until the next redeploy
                    log.warning("video upload to bucket failed job=%s: %s", job["id"], e)
            job.update(status="succeeded", size=size, error=None, finished_at=_now().isoformat())
            return repo.doc_put(tenant_id, KIND, job["id"], job) or job
        # failed / canceled: say so plainly; the provider's text can be long or technical
        log.info("video job failed job=%s status=%s error=%s", job["id"], status, str(p.get("error"))[:300])
        return _fail(tenant_id, job, "The video service could not generate this clip. "
                                     "Try a different description or image.")


# ── endpoints ─────────────────────────────────────────────────────
@router.get("/studio/videos/config")
def config(tenant_id: str = Depends(require_tenant)):
    return {"enabled": enabled(), "model": MODEL if enabled() else None, "durations": list(DURATIONS),
            "aspects": list(ASPECTS), "used": _used_this_month(tenant_id), "limit": _limit(tenant_id)}


class VideoRequest(BaseModel):
    prompt: str = Field(..., min_length=4, max_length=1500)
    image: Optional[str] = Field(None, max_length=400_000)       # data URL, ≤ ~256 KB once decoded
    duration: int = 5
    aspect: str = Field("9:16", max_length=5)


@router.post("/studio/videos")
def create(req: VideoRequest, tenant_id: str = Depends(require_tenant)):
    if not enabled():
        raise HTTPException(status_code=503, detail="AI video is not set up on this server yet.")
    if req.duration not in DURATIONS:
        raise HTTPException(status_code=422, detail=f"duration must be one of {list(DURATIONS)}")
    if req.aspect not in ASPECTS:
        raise HTTPException(status_code=422, detail=f"aspect must be one of {list(ASPECTS)}")
    if req.image and not _DATA_URL.match(req.image):
        raise HTTPException(status_code=422, detail="The image must be a JPEG, PNG or WebP picture.")
    limit = _limit(tenant_id)
    if limit is not None and _used_this_month(tenant_id) >= limit:
        raise HTTPException(status_code=402,
                            detail=f"Monthly AI video limit reached ({limit} clips on your plan). "
                                   "Upgrade for more AI video clips.")
    ratelimit.enforce("ai-video", tenant_id, limit=6, window=600,
                      detail="You're starting videos very quickly — wait for the current ones to finish.")
    running = [j for j in repo.docs_list(tenant_id, KIND, limit=50) if j.get("status") in RUNNING]
    if len(running) >= 3:
        raise HTTPException(status_code=409, detail="Three videos are already being generated — wait for one to finish.")

    me = current_user()
    job = repo.doc_add(tenant_id, KIND, {
        "status": "starting", "prompt": " ".join(req.prompt.split()), "duration": req.duration,
        "aspect": req.aspect, "has_image": bool(req.image), "created_by": me["email"] if me else "",
        "prediction_id": None, "error": None, "size": None, "finished_at": None,
    }, _now().isoformat())
    model_input = {"prompt": job["prompt"], "duration": req.duration, "resolution": RESOLUTION,
                   "aspect_ratio": req.aspect}
    if req.image:
        model_input["image"] = req.image                       # the model then follows the image's shape
    try:
        p = provider_create(model_input)
    except urllib.error.HTTPError as e:
        log.error("video create HTTP %s: %s", e.code, e.read().decode("utf-8", "replace")[:300])
        _fail(tenant_id, job, "The video service rejected the request.")
        raise HTTPException(status_code=502, detail="The AI video service is temporarily unavailable — please try again shortly.")
    except (urllib.error.URLError, TimeoutError, ValueError) as e:
        log.error("video create failed: %s", e)
        _fail(tenant_id, job, "The video service could not be reached.")
        raise HTTPException(status_code=502, detail="The AI video service is temporarily unavailable — please try again shortly.")
    job.update(prediction_id=p.get("id"), status=p.get("status") if p.get("status") in RUNNING else "starting")
    job = repo.doc_put(tenant_id, KIND, job["id"], job) or job
    activity.record(tenant_id, "video.create", job["prompt"][:60], f"{req.duration}s")
    return _public(_refresh(tenant_id, job) if p.get("status") not in RUNNING else job)


@router.get("/studio/videos")
def list_videos(tenant_id: str = Depends(require_tenant)):
    return {"items": [_public(j) for j in repo.docs_list(tenant_id, KIND, limit=60)]}


def _own(tenant_id: str, job_id: int) -> dict:
    job = repo.doc_get(tenant_id, KIND, job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Video not found")
    return job


@router.get("/studio/videos/{job_id}")
def get_video(job_id: int, tenant_id: str = Depends(require_tenant)):
    return _public(_refresh(tenant_id, _own(tenant_id, job_id)))


@router.get("/studio/videos/{job_id}/file")
def video_file(job_id: int, tenant_id: str = Depends(require_tenant)):
    job = _own(tenant_id, job_id)
    if job.get("status") == "succeeded" and job.get("stored") == "bucket" and objstore.enabled():
        return RedirectResponse(objstore.presigned_get(_object_key(tenant_id, job["id"]), expires=600,
                                                       filename=f"lumio-ai-video-{job['id']}.mp4"),
                                status_code=307)
    path = _path(tenant_id, job["id"])
    if job.get("status") != "succeeded" or not os.path.isfile(path):
        raise HTTPException(status_code=404, detail="Video not found")
    return FileResponse(path, media_type="video/mp4", filename=f"lumio-ai-video-{job['id']}.mp4")


@router.delete("/studio/videos/{job_id}")
def delete_video(job_id: int, tenant_id: str = Depends(require_tenant)):
    job = _own(tenant_id, job_id)
    if job.get("status") in RUNNING and job.get("prediction_id"):
        try:                                                     # best effort: stop paying for it
            _request("POST", f"{API_BASE}/predictions/{job['prediction_id']}/cancel", {})
        except Exception:                                        # noqa: BLE001
            pass
    try:
        os.remove(_path(tenant_id, job["id"]))
    except OSError:
        pass
    if job.get("stored") == "bucket" and objstore.enabled():
        try:
            objstore.delete(_object_key(tenant_id, job["id"]))
        except Exception:                                        # noqa: BLE001
            log.warning("could not delete bucket copy of video job=%s", job["id"])
    repo.doc_delete(tenant_id, KIND, job["id"])
    return {"deleted": True}
